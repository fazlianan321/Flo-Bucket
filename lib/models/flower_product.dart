
class FlowerProduct {
  final int id;
  final String name;
  final String category;
  final String image;
  final int price;
  final double rating;
  final String description;

  const FlowerProduct({
    required this.id,
    required this.name,
    required this.category,
    required this.image,
    required this.price,
    required this.rating,
    required this.description,
  });
}
